pub mod fingerprint; // Architecture detection and entity fingerprinting

use std::path::PathBuf; // Filesystem path representations
use std::fs; // Filesystem operations for wrapper creation
use anyhow::{Context, Result}; // Error management with contextual messages

pub use fingerprint::{ArchitectureFingerprint, ProjectFingerprinter}; // Re-export fingerprinting API

/// Statically embedded Lua bridge script included in the Courtship binary.
pub const EMBEDDED_BRIDGE_LUA: &str = include_str!("../assets/mcp_bridge.lua");

/// Minimal 5-line inline hook snippet emitted for manual integration into main.lua.
pub const SHIM_SNIPPET: &str = r#"-- [Courtship MCP Hook]
local courtship_ok, courtship = pcall(require, "mcp_bridge")
if courtship_ok and courtship.init then
    courtship.init({ port = 12345 })
end
"#;

/// Configuration options for generating a zero-touch game launcher wrapper directory.
pub struct WrapperConfig {
    /// Directory containing the original LOVE game source code.
    pub game_source_dir: PathBuf,
    /// TCP communication port used by the MCP bridge.
    pub mcp_port: u16,
    /// Destination directory where the wrapper main.lua and bridge are generated.
    pub wrapper_dir: PathBuf,
}

pub struct WrapperGenerator;

impl WrapperGenerator {
    /// Generates a temporary wrapper directory containing an injected main.lua and mcp_bridge.lua
    pub fn generate_wrapper(config: &WrapperConfig) -> Result<PathBuf> {
        fs::create_dir_all(&config.wrapper_dir)
            .context("Failed to create wrapper directory")?;

        let bridge_path = config.wrapper_dir.join("mcp_bridge.lua");
        fs::write(&bridge_path, EMBEDDED_BRIDGE_LUA)
            .context("Failed to write mcp_bridge.lua into wrapper dir")?;

        let canonical_source = config
            .game_source_dir
            .canonicalize()
            .unwrap_or_else(|_| config.game_source_dir.clone());
        let source_path_str = canonical_source.to_string_lossy().replace('\\', "/");

        let wrapper_main = format!(
            r#"-- Generated by Courtship (court run)
-- Wraps game source at: {source_path_str}

local real_source = "{source_path_str}"
local mcp_port = {port}

-- Extend package.path so real game modules can be required
package.path = real_source .. "/?.lua;" .. real_source .. "/?/init.lua;" .. package.path

-- Mount original source into love filesystem
if love and love.filesystem then
    local mount_ok = love.filesystem.mount(real_source, "game_mount", true)
    if not mount_ok then
        print("[Courtship] Warning: love.filesystem.mount fallback to package.path")
    end
end

-- Load Courtship MCP bridge
local bridge_ok, bridge = pcall(require, "mcp_bridge")
if bridge_ok and bridge.init then
    bridge.init({{ port = mcp_port }})
else
    print("[Courtship] Running in offline/mock mode")
end

-- Load target game main.lua
local real_main_path = real_source .. "/main.lua"
local real_chunk, err = loadfile(real_main_path)
if not real_chunk then
    error("[Courtship] Failed to load target game main.lua: " .. tostring(err))
end

-- Intercept love.update to process bridge input and event polling
local orig_update = love.update
love.update = function(dt)
    if bridge and bridge.poll then
        bridge.poll(dt)
    end
    if orig_update then
        orig_update(dt)
    end
end

-- Execute real game entrypoint
real_chunk()
"#,
            source_path_str = source_path_str,
            port = config.mcp_port
        );

        let main_path = config.wrapper_dir.join("main.lua");
        fs::write(&main_path, wrapper_main)
            .context("Failed to write wrapper main.lua")?;

        Ok(config.wrapper_dir.clone())
    }

    /// Emits the inline hook snippet for manual or court init workflows
    pub fn get_inline_shim(port: u16) -> String {
        SHIM_SNIPPET.replace("12345", &port.to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_wrapper_generation() {
        let temp_dir = tempfile::tempdir().unwrap();
        let target_dir = temp_dir.path().join("wrapper");
        let fake_game = temp_dir.path().join("game");
        fs::create_dir_all(&fake_game).unwrap();
        fs::write(fake_game.join("main.lua"), "function love.draw() end").unwrap();

        let cfg = WrapperConfig {
            game_source_dir: fake_game,
            mcp_port: 8080,
            wrapper_dir: target_dir.clone(),
        };

        let out = WrapperGenerator::generate_wrapper(&cfg).unwrap();
        assert!(out.exists());
        assert!(target_dir.join("main.lua").exists());
        assert!(target_dir.join("mcp_bridge.lua").exists());
    }

    #[test]
    fn test_inline_shim() {
        let shim = WrapperGenerator::get_inline_shim(9999);
        assert!(shim.contains("9999"));
        assert!(shim.contains("mcp_bridge"));
    }
}
